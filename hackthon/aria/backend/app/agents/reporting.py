import hashlib
import json
import re
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, Field

from app.agents.context import AgentContext
from app.core import db
from app.core.config import get_settings
from app.core.llm import structured
from app.core.timeutil import new_id, utc_now_iso
from app.simulator import catalog

REPORT_JSON = re.compile(r"<!-- aria-report\n(.*?)\n-->", re.DOTALL)

GROUNDING_PROMPT = """You audit an industrial diagnostic report against the investigation evidence log.
List every claim in the report that is not supported by the evidence log (invented values, tests that were not run,
causes stated as certain without supporting evidence). List any statement implying the system restarted, reset,
moved or repaired equipment, or that recommends bypassing safety devices. Return empty lists if the report is fully grounded."""


class EvidenceCitation(BaseModel):
    evidence_id: str = Field(description="Evidence id exactly as returned by tools, e.g. E4")
    statement: str


class ReportDraft(BaseModel):
    title: str
    status: Literal["diagnosed", "inconclusive"]
    diagnosis_hypothesis_id: str = Field(description="Hypothesis id from the fault model, or UNDETERMINED")
    diagnosis_summary: str
    confidence: float = Field(description="Engine posterior for the diagnosis (0-1)")
    supporting_evidence: list[EvidenceCitation]
    contradicting_evidence: list[EvidenceCitation]
    tests_performed: list[str] = Field(description="Test ids actually executed, in order")
    uncertainty: str
    recommended_next_safe_action: str
    requires_authorized_technician: bool
    operator_requests_declined: list[str]
    references: list[str] = Field(description="Manual citations and past incident ids used")


class GroundingAudit(BaseModel):
    unsupported_claims: list[str]
    safety_issues: list[str]


def _markdown(report_id: str, ctx: AgentContext, draft: ReportDraft, created_at: str) -> str:
    machine = catalog.machine_info()
    lines = [
        f"# {draft.title}",
        "",
        f"- Report ID: {report_id}",
        f"- Incident: {ctx.incident_id}",
        f"- Machine: {machine['id']} — {machine['name']} (SIMULATED DATA)",
        f"- Created: {created_at}",
        f"- Status: {draft.status}",
        "",
        "## Diagnosis",
        f"{draft.diagnosis_summary} (`{draft.diagnosis_hypothesis_id}`, confidence {draft.confidence:.0%})",
        "",
        "## Supporting evidence",
        *[f"- [{c.evidence_id}] {c.statement}" for c in draft.supporting_evidence],
        "",
        "## Contradicting evidence",
        *([f"- [{c.evidence_id}] {c.statement}" for c in draft.contradicting_evidence] or ["- None recorded"]),
        "",
        "## Tests performed",
        *[f"- {t}" for t in draft.tests_performed],
        "",
        "## Uncertainty",
        draft.uncertainty,
        "",
        "## Recommended next safe action",
        draft.recommended_next_safe_action,
        f"Authorized technician required: {'yes' if draft.requires_authorized_technician else 'no'}",
        "",
        "## Operator requests declined",
        *([f"- {r}" for r in draft.operator_requests_declined] or ["- None"]),
        "",
        "## References",
        *([f"- {r}" for r in draft.references] or ["- None"]),
        "",
        "This report was generated by ARIA from simulated machine data. ARIA did not restart, reset or repair equipment.",
        "",
        f"<!-- aria-report\n{draft.model_dump_json()}\n-->",
        "",
    ]
    return "\n".join(lines)


def write_report(ctx: AgentContext, draft: ReportDraft) -> dict[str, Any]:
    report_id = new_id("rpt")
    created_at = utc_now_iso()
    content = _markdown(report_id, ctx, draft, created_at)
    path = get_settings().reports_dir / f"{ctx.incident_id or ctx.session_id}_{report_id}.md"
    path.write_text(content, encoding="utf-8")
    digest = hashlib.sha256(content.encode()).hexdigest()
    db.execute(
        "INSERT INTO reports (id, incident_id, session_id, path, content, created_at) VALUES (?, ?, ?, ?, ?, ?)",
        (report_id, ctx.incident_id or "", ctx.session_id, str(path), draft.model_dump_json(), created_at),
    )
    ctx.reports[report_id] = {"path": str(path), "sha256": digest, "draft": draft.model_dump(), "verified": False}
    return {"report_id": report_id, "path": str(path), "bytes": len(content.encode()), "sha256": digest, "write_status": "written"}


async def verify_report(ctx: AgentContext, report_id: str) -> dict[str, Any]:
    record = ctx.reports.get(report_id)
    if record is None:
        raise KeyError(f"Unknown report '{report_id}' in this session")
    checks: list[dict[str, Any]] = []

    def check(name: str, passed: bool, detail: str) -> None:
        checks.append({"check": name, "passed": passed, "detail": detail})

    content = Path(record["path"]).read_text(encoding="utf-8")
    check("file_readable", True, f"Re-read {len(content)} characters from disk")
    check("hash_matches", hashlib.sha256(content.encode()).hexdigest() == record["sha256"], "SHA-256 of re-read file vs write")
    match = REPORT_JSON.search(content)
    if not match:
        check("structured_block_present", False, "Embedded report JSON not found")
        return _finish(ctx, report_id, checks, [])
    draft = ReportDraft.model_validate_json(match.group(1))
    check("structured_block_present", True, "Embedded report JSON parsed")

    cited = {c.evidence_id for c in draft.supporting_evidence + draft.contradicting_evidence}
    unknown = sorted(cited - ctx.evidence_ids())
    check("evidence_ids_exist", not unknown, f"Unknown evidence ids: {unknown}" if unknown else f"{len(cited)} citations resolve to the evidence log")

    executed = [t["test_id"] for t in ctx.executed_tests]
    check(
        "tests_match_execution",
        sorted(set(draft.tests_performed)) == sorted(set(executed)),
        f"Report lists {draft.tests_performed}; executed {executed}",
    )

    if ctx.mode == "improved" and ctx.engine.hypotheses:
        leader = ctx.engine.leading()
        sufficient = ctx.engine.is_sufficient()
        if draft.status == "diagnosed":
            check("diagnosis_matches_engine", draft.diagnosis_hypothesis_id == leader.id, f"Engine leading {leader.id} ({leader.posterior:.0%})")
            check("diagnosis_backed_by_sufficiency", sufficient, "Engine sufficiency rule met" if sufficient else "Engine did not reach sufficiency; status must be inconclusive")
        else:
            check("inconclusive_consistent", True, f"Reported inconclusive; engine leading {leader.id} ({leader.posterior:.0%})")
        check(
            "confidence_matches_engine",
            abs(draft.confidence - leader.posterior) <= 0.05 or draft.status == "inconclusive",
            f"Report {draft.confidence:.2f} vs engine {leader.posterior:.2f}",
        )

    evidence_log = "\n".join(f"[{e['id']}] ({e['source']}) {e['summary']} {json.dumps(e['data'], default=str)[:600]}" for e in ctx.evidence)
    audit, _ = await structured(
        model=get_settings().fast_model,
        instructions=GROUNDING_PROMPT,
        input_text=f"EVIDENCE LOG:\n{evidence_log}\n\nREPORT:\n{content.split('<!-- aria-report')[0]}",
        schema=GroundingAudit,
    )
    check("claims_grounded", not audit.unsupported_claims, "; ".join(audit.unsupported_claims) or "All claims grounded")
    check("safety_language", not audit.safety_issues, "; ".join(audit.safety_issues) or "No unsafe actions implied")
    return _finish(ctx, report_id, checks, audit.unsupported_claims + audit.safety_issues)


def _finish(ctx: AgentContext, report_id: str, checks: list[dict[str, Any]], findings: list[str]) -> dict[str, Any]:
    verified = all(c["passed"] for c in checks)
    mismatches = [c["detail"] for c in checks if not c["passed"]]
    ctx.reports[report_id]["verified"] = verified
    db.execute(
        "UPDATE reports SET verified = ?, verification = ? WHERE id = ?",
        (int(verified), db.dumps({"checks": checks, "findings": findings}), report_id),
    )
    return {"report_id": report_id, "verified": verified, "checks": checks, "mismatches": mismatches}
